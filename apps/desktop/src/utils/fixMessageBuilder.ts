/**
 * Formats a Date into FIX UTCTimestamp (`YYYYMMDD-HH:MM:SS.sss`).
 */
export function formatFixUtcTimestamp(date: Date = new Date()): string {
  return `${formatFixUtcDate(date)}-${formatFixUtcTime(date)}`;
}

/**
 * Formats a Date into FIX UTCDateOnly / LocalMktDate (`YYYYMMDD`).
 */
export function formatFixUtcDate(date: Date = new Date()): string {
  const y = String(date.getUTCFullYear()).padStart(4, '0');
  const m = String(date.getUTCMonth() + 1).padStart(2, '0');
  const d = String(date.getUTCDate()).padStart(2, '0');
  return `${y}${m}${d}`;
}

/**
 * Formats a Date into FIX UTCTimeOnly (`HH:MM:SS.sss`).
 */
export function formatFixUtcTime(date: Date = new Date()): string {
  const hh = String(date.getUTCHours()).padStart(2, '0');
  const mm = String(date.getUTCMinutes()).padStart(2, '0');
  const ss = String(date.getUTCSeconds()).padStart(2, '0');
  const ms = String(date.getUTCMilliseconds()).padStart(3, '0');
  return `${hh}:${mm}:${ss}.${ms}`;
}

/**
 * Generates a unique request/order identifier (UUID v4 when Web Crypto is available).
 */
export function generateFixFieldId(uuidFactory?: () => string): string {
  if (uuidFactory) return uuidFactory();
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID();
  }
  const random = Math.random().toString(16).slice(2, 10);
  return `fix-${Date.now().toString(36)}-${random}`;
}

/**
 * Returns whether a field benefits from a 1-click unique ID generator.
 */
export function isIdLikeFixField(tag: number, name?: string): boolean {
  if (ID_LIKE_TAGS.has(tag)) return true;
  if (!name) return false;
  return /(?:ReqID|OrdID|ReportID|QuoteID|AllocID|ListID)$/i.test(name);
}

/**
 * Returns the quick-fill temporal kind for a FIX datatype, if any.
 */
export function getFixTemporalKind(
  type?: string
): 'timestamp' | 'date' | 'time' | null {
  if (!type) return null;
  if (type === 'UTCTimestamp') return 'timestamp';
  if (type === 'UTCDateOnly' || type === 'UTCDate' || type === 'LocalMktDate') {
    return 'date';
  }
  if (type === 'UTCTimeOnly') return 'time';
  return null;
}

/**
 * Produces a concise placeholder hint for a FIX field input based on its datatype.
 */
export function getFixFieldPlaceholder(definition?: FixFieldDefinition): string {
  if (!definition) return 'Value or {{VAR}}';
  if (definition.enumValues && definition.enumValues.length > 0) {
    const first = definition.enumValues[0];
    return `Select or type (e.g. ${first.value})`;
  }
  switch (definition.type) {
    case 'UTCTimestamp':
      return 'YYYYMMDD-HH:MM:SS.sss';
    case 'UTCDateOnly':
    case 'UTCDate':
    case 'LocalMktDate':
      return 'YYYYMMDD';
    case 'UTCTimeOnly':
      return 'HH:MM:SS.sss';
    case 'MonthYear':
      return 'YYYYMM';
    case 'Boolean':
      return 'Y or N';
    case 'Price':
    case 'PriceOffset':
    case 'Amt':
    case 'Qty':
    case 'float':
    case 'Percentage':
      return `${definition.type} (e.g. 10.5)`;
    case 'int':
    case 'SeqNum':
    case 'Length':
    case 'NumInGroup':
      return `${definition.type} (e.g. 1)`;
    case 'Currency':
      return 'ISO 4217 (e.g. USD)';
    default:
      return `${definition.type || 'String'} or {{VAR}}`;
  }
}

/**
 * Builds a concise entry summary for a builder repeating-group entry row.
 */
export function buildBuilderEntrySummary(
  entry: FixBuilderGroupEntry,
  dictionary?: FixDictionary | null
): string {
  const parts: string[] = [];
  for (const field of entry.fields) {
    const raw = field.value.trim();
    if (!raw) continue;
    const def = dictionary?.fieldByTag(field.tag);
    const enumMatch = def?.enumValues?.find((candidate) => candidate.value === raw);
    parts.push(
      enumMatch
        ? `${raw} · ${enumMatch.name.replace(/_+/g, ' ')}`
        : raw
    );
    if (parts.length >= 3) break;
  }
  return parts.join(' · ') || 'Empty entry';
}

