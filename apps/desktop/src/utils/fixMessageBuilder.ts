interface ExpandedScope {
  fields: FixSchemaField[];
  groups: FixSchemaGroup[];
  fieldByTag: Map<number, FixSchemaField>;
  groupByCounterTag: Map<number, FixSchemaGroup>;
  orderedSlots: Array<{ kind: 'field'; tag: number } | { kind: 'group'; counterTag: number }>;
}

function expandMembers(
  dictionary: FixDictionary,
  members: FixMemberRef[],
  parentReqd: FixReqd,
  componentPath: string | undefined,
  requiredComponent: string | undefined,
  seenComponents: Set<string>,
  orderCounter: { value: number },
  requiredComponentTags: Map<string, Set<number>>,
  promoteFirstAsStarter: boolean
): ExpandedScope {
  const fields: FixSchemaField[] = [];
  const groups: FixSchemaGroup[] = [];
  const fieldByTag = new Map<number, FixSchemaField>();
  const groupByCounterTag = new Map<number, FixSchemaGroup>();
  const orderedSlots: Array<
    { kind: 'field'; tag: number } | { kind: 'group'; counterTag: number }
  > = [];

  let promotedDone = !promoteFirstAsStarter;

  for (const member of members) {
    if (member.kind === 'component') {
      if (isEnvelopeComponent(member.name)) continue;
      if (seenComponents.has(member.name)) continue;
      const component = dictionary.componentByName(member.name);
      if (!component) continue;

      const effReqd = combineReqd(parentReqd, member.reqd);
      const nextSeen = new Set(seenComponents);
      nextSeen.add(member.name);
      const nextPath = componentPath ? `${componentPath} · ${member.name}` : member.name;

      // Determine whether this required component has any direct reqd='Y' members.
      // If not (e.g. FIX 4.4 Instrument or OrderQtyData), promote its first wire
      // member as starter and track all its tags as satisfying the component.
      const needsStarterPromotion =
        (effReqd === 'Y' || !promotedDone) &&
        !componentHasRequiredDirectMember(dictionary, component.members, new Set(nextSeen));

      const nextRequiredComp =
        effReqd === 'Y' && needsStarterPromotion ? member.name : requiredComponent;

      const sub = expandMembers(
        dictionary,
        component.members,
        effReqd,
        nextPath,
        nextRequiredComp,
        nextSeen,
        orderCounter,
        requiredComponentTags,
        needsStarterPromotion
      );

      if (effReqd === 'Y' && needsStarterPromotion) {
        const compTagSet = requiredComponentTags.get(member.name) || new Set<number>();
        for (const f of sub.fields) compTagSet.add(f.tag);
        for (const g of sub.groups) compTagSet.add(g.counterTag);
        requiredComponentTags.set(member.name, compTagSet);
      }

      if (!promotedDone && (sub.fields.length > 0 || sub.groups.length > 0)) {
        promotedDone = true;
      }

      for (const slot of sub.orderedSlots) {
        if (slot.kind === 'field') {
          const subField = sub.fieldByTag.get(slot.tag);
          if (!subField) continue;
          addOrMergeField(fields, fieldByTag, orderedSlots, subField);
        } else {
          const subGroup = sub.groupByCounterTag.get(slot.counterTag);
          if (!subGroup) continue;
          addOrMergeGroup(groups, groupByCounterTag, orderedSlots, subGroup);
        }
      }
      continue;
    }

    if (member.kind === 'field') {
      if (FIX_SESSION_ENVELOPE_TAGS.has(member.tag) || member.tag === 35) continue;
      const effReqd = combineReqd(parentReqd, member.reqd);
      const definition = dictionary.fieldByTag(member.tag);
      const isStarter = effReqd === 'Y' || !promotedDone;
      if (!promotedDone) promotedDone = true;

      const schemaField: FixSchemaField = {
        kind: 'field',
        tag: member.tag,
        name: definition?.name || `Tag ${member.tag}`,
        reqd: effReqd,
        isStarter,
        componentPath,
        requiredComponent: isStarter && effReqd !== 'Y' ? requiredComponent : undefined,
        wireOrder: orderCounter.value++,
        definition,
      };
      addOrMergeField(fields, fieldByTag, orderedSlots, schemaField);
      continue;
    }

    if (member.kind === 'group') {
      const effReqd = combineReqd(parentReqd, member.reqd);
      const counterDef = dictionary.fieldByTag(member.counterTag);
      const delimiterTag = dictionary.groupDelimiter(member);
      const isStarter = effReqd === 'Y' || !promotedDone;
      if (!promotedDone) promotedDone = true;

      const childRequiredCompTags = new Map<string, Set<number>>();
      const nested = expandMembers(
        dictionary,
        member.members,
        'Y',
        undefined,
        undefined,
        new Set(seenComponents),
        { value: 0 },
        childRequiredCompTags,
        false
      );

      // Ensure delimiter tag is marked as delimiter and starter inside the group.
      if (delimiterTag !== undefined) {
        const delimField = nested.fieldByTag.get(delimiterTag);
        if (delimField) {
          delimField.isDelimiter = true;
          delimField.isStarter = true;
        }
      }

      const schemaGroup: FixSchemaGroup = {
        kind: 'group',
        counterTag: member.counterTag,
        name: counterDef?.name || `Group ${member.counterTag}`,
        reqd: effReqd,
        isStarter,
        delimiterTag,
        componentPath,
        requiredComponent: isStarter && effReqd !== 'Y' ? requiredComponent : undefined,
        wireOrder: orderCounter.value++,
        fields: nested.fields,
        groups: nested.groups,
        fieldByTag: nested.fieldByTag,
        groupByCounterTag: nested.groupByCounterTag,
        orderedSlots: nested.orderedSlots,
        definition: counterDef,
      };
      addOrMergeGroup(groups, groupByCounterTag, orderedSlots, schemaGroup);
    }
  }

  return { fields, groups, fieldByTag, groupByCounterTag, orderedSlots };
}

function addOrMergeField(
  fields: FixSchemaField[],
  fieldByTag: Map<number, FixSchemaField>,
  orderedSlots: Array<{ kind: 'field'; tag: number } | { kind: 'group'; counterTag: number }>,
  candidate: FixSchemaField
): void {
  const existing = fieldByTag.get(candidate.tag);
  if (!existing) {
    fields.push(candidate);
    fieldByTag.set(candidate.tag, candidate);
    orderedSlots.push({ kind: 'field', tag: candidate.tag });
  } else {
    existing.reqd = maxReqd(existing.reqd, candidate.reqd);
    existing.isStarter = existing.isStarter || candidate.isStarter;
    existing.isDelimiter = existing.isDelimiter || candidate.isDelimiter;
  }
}

function addOrMergeGroup(
  groups: FixSchemaGroup[],
  groupByCounterTag: Map<number, FixSchemaGroup>,
  orderedSlots: Array<{ kind: 'field'; tag: number } | { kind: 'group'; counterTag: number }>,
  candidate: FixSchemaGroup
): void {
  const existing = groupByCounterTag.get(candidate.counterTag);
  if (!existing) {
    groups.push(candidate);
    groupByCounterTag.set(candidate.counterTag, candidate);
    orderedSlots.push({ kind: 'group', counterTag: candidate.counterTag });
  } else {
    existing.reqd = maxReqd(existing.reqd, candidate.reqd);
    existing.isStarter = existing.isStarter || candidate.isStarter;
  }
}

function combineReqd(parent: FixReqd, child: FixReqd): FixReqd {
  if (parent === 'Y') return child;
  if (parent === 'C') return child === 'N' ? 'N' : 'C';
  return 'N';
}

function maxReqd(a: FixReqd, b: FixReqd): FixReqd {
  if (a === 'Y' || b === 'Y') return 'Y';
  if (a === 'C' || b === 'C') return 'C';
  return 'N';
}

function isEnvelopeComponent(name: string): boolean {
  return /standard.*header|message header|standard.*trailer|message trailer/i.test(name);
}

function componentHasRequiredDirectMember(
  dictionary: FixDictionary,
  members: FixMemberRef[],
  seen: Set<string>
): boolean {
  for (const member of members) {
    if (member.kind === 'field' && member.reqd === 'Y') return true;
    if (member.kind === 'group' && member.reqd === 'Y') return true;
    if (
      member.kind === 'component' &&
      member.reqd === 'Y' &&
      !isEnvelopeComponent(member.name) &&
      !seen.has(member.name)
    ) {
      const nested = dictionary.componentByName(member.name);
      if (!nested) continue;
      const nextSeen = new Set(seen);
      nextSeen.add(member.name);
      if (componentHasRequiredDirectMember(dictionary, nested.members, nextSeen)) {
        return true;
      }
    }
  }
  return false;
}

function hydrateScopeFromNodes(
  nodes: FixParsedNode[],
  scope: Pick<FixMessageSchema, 'fields' | 'groups' | 'fieldByTag' | 'groupByCounterTag'>,
  delimiterTag?: number
): { fields: FixBuilderField[]; groups: FixBuilderGroup[] } {
  const matchedSchemaFields = new Map<number, string>();
  const extraFields: FixBuilderField[] = [];
  const parsedGroups = new Map<number, FixParsedGroupNode>();

  for (const node of nodes) {
    if (node.kind === 'field') {
      if (scope.fieldByTag.has(node.tag) && !matchedSchemaFields.has(node.tag)) {
        matchedSchemaFields.set(node.tag, node.value);
      } else {
        extraFields.push({ tag: node.tag, value: node.value, isExtra: true });
      }
    } else if (node.kind === 'group') {
      parsedGroups.set(node.counterTag, node);
    }
  }

  const fields: FixBuilderField[] = [];
  const addedTags = new Set<number>();

  // If inside a repeating group, pin delimiter tag first unconditionally.
  if (delimiterTag !== undefined) {
    fields.push({
      tag: delimiterTag,
      value: matchedSchemaFields.get(delimiterTag) ?? '',
    });
    addedTags.add(delimiterTag);
  }

  for (const schemaField of scope.fields) {
    if (addedTags.has(schemaField.tag)) continue;
    if (matchedSchemaFields.has(schemaField.tag)) {
      fields.push({
        tag: schemaField.tag,
        value: matchedSchemaFields.get(schemaField.tag)!,
      });
      addedTags.add(schemaField.tag);
    } else if (schemaField.isStarter) {
      fields.push({ tag: schemaField.tag, value: '' });
      addedTags.add(schemaField.tag);
    }
  }

  for (const extra of extraFields) {
    fields.push(extra);
  }

  const groups: FixBuilderGroup[] = [];
  for (const groupSchema of scope.groups) {
    const parsedGroup = parsedGroups.get(groupSchema.counterTag);
    if (parsedGroup && parsedGroup.entries.length > 0) {
      groups.push({
        counterTag: groupSchema.counterTag,
        entries: parsedGroup.entries.map((entry) => {
          const hydrated = hydrateScopeFromNodes(
            entry.nodes,
            groupSchema,
            groupSchema.delimiterTag
          );
          return {
            id: createFixGroupEntryId(),
            fields: hydrated.fields,
            groups: hydrated.groups,
          };
        }),
      });
    } else if (groupSchema.isStarter) {
      groups.push({
        counterTag: groupSchema.counterTag,
        entries: [createEmptyGroupEntry(groupSchema)],
      });
    }
  }

  return { fields, groups };
}

function collectNonEmptyFromGroups(
  groups: FixBuilderGroup[],
  tagValues: Map<number, string>,
  groupsByCounter: Map<number, FixBuilderGroup>
): void {
  for (const group of groups) {
    if (!groupsByCounter.has(group.counterTag)) {
      groupsByCounter.set(group.counterTag, group);
    }
    for (const entry of group.entries) {
      for (const field of entry.fields) {
        if (field.value !== '' && !tagValues.has(field.tag)) {
          tagValues.set(field.tag, field.value);
        }
      }
      collectNonEmptyFromGroups(entry.groups, tagValues, groupsByCounter);
    }
  }
}

function hasNonEmptyGroupEntry(entry: FixBuilderGroupEntry): boolean {
  if (entry.fields.some((f) => f.value !== '')) return true;
  return entry.groups.some((g) => g.entries.some(hasNonEmptyGroupEntry));
}

function alignGroupEntryToSchema(
  entry: FixBuilderGroupEntry,
  groupSchema: FixSchemaGroup
): FixBuilderGroupEntry {
  const existingByTag = new Map<number, string>();
  const extras: FixBuilderField[] = [];
  for (const field of entry.fields) {
    if (groupSchema.fieldByTag.has(field.tag) && !existingByTag.has(field.tag)) {
      existingByTag.set(field.tag, field.value);
    } else if (field.value !== '') {
      extras.push({ tag: field.tag, value: field.value, isExtra: true });
    }
  }

  const fields: FixBuilderField[] = [];
  const added = new Set<number>();
  if (groupSchema.delimiterTag !== undefined) {
    fields.push({
      tag: groupSchema.delimiterTag,
      value: existingByTag.get(groupSchema.delimiterTag) ?? '',
    });
    added.add(groupSchema.delimiterTag);
  }
  for (const schemaField of groupSchema.fields) {
    if (added.has(schemaField.tag)) continue;
    if (existingByTag.has(schemaField.tag)) {
      fields.push({ tag: schemaField.tag, value: existingByTag.get(schemaField.tag)! });
      added.add(schemaField.tag);
    } else if (schemaField.isStarter) {
      fields.push({ tag: schemaField.tag, value: '' });
      added.add(schemaField.tag);
    }
  }
  fields.push(...extras);

  const existingNested = new Map(entry.groups.map((g) => [g.counterTag, g]));
  const groups: FixBuilderGroup[] = [];
  for (const nestedSchema of groupSchema.groups) {
    const existing = existingNested.get(nestedSchema.counterTag);
    if (existing && existing.entries.some(hasNonEmptyGroupEntry)) {
      groups.push({
        counterTag: nestedSchema.counterTag,
        entries: existing.entries
          .filter(hasNonEmptyGroupEntry)
          .map((nestedEntry) => alignGroupEntryToSchema(nestedEntry, nestedSchema)),
      });
    } else if (nestedSchema.isStarter) {
      groups.push({
        counterTag: nestedSchema.counterTag,
        entries: [createEmptyGroupEntry(nestedSchema)],
      });
    }
  }

  return {
    id: entry.id || createFixGroupEntryId(),
    fields,
    groups,
  };
}

function appendGroupPairs(
  group: FixBuilderGroup,
  groupSchema: FixSchemaGroup | undefined,
  pairs: Array<[number, string]>
): void {
  const serializedEntries: Array<Array<[number, string]>> = [];

  for (const entry of group.entries) {
    const entryPairs: Array<[number, string]> = [];
    if (!groupSchema) {
      for (const field of entry.fields) {
        if (field.value !== '') entryPairs.push([field.tag, field.value]);
      }
      for (const nested of entry.groups) {
        appendGroupPairs(nested, undefined, entryPairs);
      }
    } else {
      const byTag = new Map<number, FixBuilderField[]>();
      const extras: FixBuilderField[] = [];
      for (const field of entry.fields) {
        if (!field.isExtra && groupSchema.fieldByTag.has(field.tag)) {
          const list = byTag.get(field.tag) || [];
          list.push(field);
          byTag.set(field.tag, list);
        } else {
          extras.push(field);
        }
      }
      const nestedByCounter = new Map(entry.groups.map((g) => [g.counterTag, g]));

      // Emit delimiter tag strictly first when non-empty.
      const emittedDelimiter = new Set<number>();
      if (groupSchema.delimiterTag !== undefined) {
        const delimFields = byTag.get(groupSchema.delimiterTag);
        if (delimFields) {
          for (const f of delimFields) {
            if (f.value !== '') entryPairs.push([f.tag, f.value]);
          }
          emittedDelimiter.add(groupSchema.delimiterTag);
        }
      }

      for (const slot of groupSchema.orderedSlots) {
        if (slot.kind === 'field') {
          if (emittedDelimiter.has(slot.tag)) continue;
          const list = byTag.get(slot.tag);
          if (!list) continue;
          for (const f of list) {
            if (f.value !== '') entryPairs.push([f.tag, f.value]);
          }
        } else {
          const nested = nestedByCounter.get(slot.counterTag);
          const nestedSchema = groupSchema.groupByCounterTag.get(slot.counterTag);
          if (nested) {
            appendGroupPairs(nested, nestedSchema, entryPairs);
          }
        }
      }

      for (const extra of extras) {
        if (extra.value !== '') entryPairs.push([extra.tag, extra.value]);
      }
    }

    if (entryPairs.length > 0) {
      serializedEntries.push(entryPairs);
    }
  }

  if (serializedEntries.length === 0) return;

  pairs.push([group.counterTag, String(serializedEntries.length)]);
  for (const entryPairs of serializedEntries) {
    pairs.push(...entryPairs);
  }
}

function validateGroupState(
  groupSchema: FixSchemaGroup,
  groupState: FixBuilderGroup | undefined,
  missingRequired: FixBuilderValidationIssue[],
  delimiterWarnings: FixBuilderValidationIssue[],
  parentContext: string | undefined
): void {
  const nonEmptyEntries = (groupState?.entries || []).filter(hasNonEmptyGroupEntry);
  if (groupSchema.isStarter && nonEmptyEntries.length === 0) {
    missingRequired.push({
      tag: groupSchema.counterTag,
      name: groupSchema.name,
      reason: 'Required repeating group has no filled entries',
      context: parentContext,
    });
    return;
  }

  (groupState?.entries || []).forEach((entry, index) => {
    if (!hasNonEmptyGroupEntry(entry)) return;
    const entryContext = parentContext
      ? `${parentContext} › ${groupSchema.name}[${index + 1}]`
      : `${groupSchema.name}[${index + 1}]`;
    const filledTags = new Set(
      entry.fields.filter((f) => f.value.trim() !== '').map((f) => f.tag)
    );

    if (
      groupSchema.delimiterTag !== undefined &&
      !filledTags.has(groupSchema.delimiterTag)
    ) {
      const delimDef = groupSchema.fieldByTag.get(groupSchema.delimiterTag);
      delimiterWarnings.push({
        tag: groupSchema.delimiterTag,
        name: delimDef?.name || `Tag ${groupSchema.delimiterTag}`,
        reason: 'Group delimiter field must be populated first for valid FIX framing',
        context: entryContext,
      });
    }

    for (const schemaField of groupSchema.fields) {
      if (schemaField.reqd === 'Y' && !filledTags.has(schemaField.tag)) {
        missingRequired.push({
          tag: schemaField.tag,
          name: schemaField.name,
          reason: 'Required group field is empty',
          context: entryContext,
        });
      }
    }

    const nestedByCounter = new Map(entry.groups.map((g) => [g.counterTag, g]));
    for (const nestedSchema of groupSchema.groups) {
      validateGroupState(
        nestedSchema,
        nestedByCounter.get(nestedSchema.counterTag),
        missingRequired,
        delimiterWarnings,
        entryContext
      );
    }
  });
}

function scoreFieldSearch(
  tag: number,
  name: string,
  componentPath: string | undefined,
  rawQuery: string,
  lowerQuery: string
): number {
  if (!rawQuery) return 100;
  const tagText = String(tag);
  const nameLower = name.toLowerCase();
  const compLower = (componentPath || '').toLowerCase();

  if (tagText === rawQuery) return 1000;
  if (tagText.startsWith(rawQuery)) return 800;
  if (nameLower === lowerQuery) return 900;
  if (nameLower.startsWith(lowerQuery)) return 700;
  if (nameLower.includes(lowerQuery)) return 500;
  if (compLower.includes(lowerQuery)) return 300;
  if (tagText.includes(rawQuery)) return 250;
  return -1;
}
