/**
 * Loads the persisted FIX message editor mode. Defaults to `'advanced'`.
 */
export function getStoredFixEditorMode(
  storage?: Pick<Storage, 'getItem'> | null
): FixMessageEditorMode {
  const target =
    storage === undefined
      ? typeof window !== 'undefined'
        ? window.localStorage
        : null
      : storage;
  if (!target) return DEFAULT_FIX_EDITOR_MODE;
  try {
    const stored = target.getItem(FIX_EDITOR_MODE_STORAGE_KEY);
    if (stored === 'raw' || stored === 'advanced') return stored;
    return DEFAULT_FIX_EDITOR_MODE;
  } catch {
    return DEFAULT_FIX_EDITOR_MODE;
  }
}

/**
 * Persists the FIX message editor mode preference.
 */
export function setStoredFixEditorMode(
  mode: FixMessageEditorMode,
  storage?: Pick<Storage, 'setItem'> | null
): void {
  const target =
    storage === undefined
      ? typeof window !== 'undefined'
        ? window.localStorage
        : null
      : storage;
  if (!target) return;
  try {
    target.setItem(FIX_EDITOR_MODE_STORAGE_KEY, mode);
  } catch {
    // Ignore blocked storage backends.
  }
}

/**
 * Loads the persisted Advanced composer split height percentage.
 */
export function getStoredFixComposerHeightPct(
  storage?: Pick<Storage, 'getItem'> | null
): number {
  const target =
    storage === undefined
      ? typeof window !== 'undefined'
        ? window.localStorage
        : null
      : storage;
  if (!target) return DEFAULT_FIX_COMPOSER_HEIGHT_PCT;
  try {
    const raw = target.getItem(FIX_COMPOSER_HEIGHT_STORAGE_KEY);
    const parsed = raw !== null ? Number(raw) : Number.NaN;
    if (!Number.isFinite(parsed)) return DEFAULT_FIX_COMPOSER_HEIGHT_PCT;
    return clampComposerHeightPct(parsed);
  } catch {
    return DEFAULT_FIX_COMPOSER_HEIGHT_PCT;
  }
}

/**
 * Persists the Advanced composer split height percentage.
 */
export function setStoredFixComposerHeightPct(
  percent: number,
  storage?: Pick<Storage, 'setItem'> | null
): void {
  const target =
    storage === undefined
      ? typeof window !== 'undefined'
        ? window.localStorage
        : null
      : storage;
  if (!target) return;
  try {
    target.setItem(
      FIX_COMPOSER_HEIGHT_STORAGE_KEY,
      String(Math.round(clampComposerHeightPct(percent)))
    );
  } catch {
    // Ignore blocked storage backends.
  }
}

export function clampComposerHeightPct(percent: number): number {
  return Math.max(
    MIN_FIX_COMPOSER_HEIGHT_PCT,
    Math.min(MAX_FIX_COMPOSER_HEIGHT_PCT, percent)
  );
}

/**
 * Lists all application-level FIX messages in the active dictionary,
 * excluding session-managed administrative messages.
 */
export function listFixApplicationMessages(
  dictionary: FixDictionary
): FixApplicationMessageOption[] {
  const seen = new Set<string>();
  const options: FixApplicationMessageOption[] = [];

  for (const message of dictionary.data.messages) {
    if (message.category !== 'app') continue;
    if (FIX_ADMIN_MESSAGE_TYPES.has(message.msgType)) continue;
    if (seen.has(message.msgType)) continue;
    seen.add(message.msgType);
    options.push({
      msgType: message.msgType,
      name: message.name,
      label: formatFixMessageName(message.name),
      isCommon: COMMON_MSG_ORDER.has(message.msgType),
    });
  }

  return options.sort((a, b) => {
    const aCommon = COMMON_MSG_ORDER.get(a.msgType);
    const bCommon = COMMON_MSG_ORDER.get(b.msgType);
    if (aCommon !== undefined && bCommon !== undefined) return aCommon - bCommon;
    if (aCommon !== undefined) return -1;
    if (bCommon !== undefined) return 1;
    return a.label.localeCompare(b.label);
  });
}

/**
 * Searches application FIX messages by MsgType code, readable label, CamelCase
 * name, or initials (e.g. `mdr` -> Market Data Request, `nos` -> New Order Single).
 */
export function searchFixApplicationMessages(
  dictionary: FixDictionary,
  query: string
): FixApplicationMessageOption[] {
  const all = listFixApplicationMessages(dictionary);
  const trimmed = query.trim();
  if (!trimmed) return all;

  const lower = trimmed.toLowerCase();
  const scored: Array<{ option: FixApplicationMessageOption; score: number }> = [];

  for (const option of all) {
    const codeLower = option.msgType.toLowerCase();
    const labelLower = option.label.toLowerCase();
    const nameLower = option.name.toLowerCase();
    const initials = option.label
      .split(/\s+/)
      .map((word) => word[0] || '')
      .join('')
      .toLowerCase();

    let score = -1;
    if (option.msgType === trimmed) score = 1000;
    else if (codeLower === lower) score = 950;
    else if (codeLower.startsWith(lower)) score = 850;
    else if (labelLower.startsWith(lower) || nameLower.startsWith(lower)) score = 750;
    else if (initials === lower) score = 700;
    else if (initials.startsWith(lower)) score = 650;
    else if (labelLower.includes(lower) || nameLower.includes(lower)) score = 500;
    else if (codeLower.includes(lower)) score = 400;

    if (score >= 0) {
      if (option.isCommon) score += 25;
      scored.push({ option, score });
    }
  }

  scored.sort((a, b) => b.score - a.score || a.option.label.localeCompare(b.option.label));
  return scored.map((entry) => entry.option);
}

const schemaCache = new WeakMap<FixDictionary, Map<string, FixMessageSchema | null>>();

/**
 * Expands a dictionary message definition into a structured, wire-ordered schema
 * of fields and repeating groups suitable for the Advanced Message Builder.
 */
export function getFixMessageSchema(
  dictionary: FixDictionary,
  msgType: string
): FixMessageSchema | null {
  if (!msgType) return null;
  let perDict = schemaCache.get(dictionary);
  if (!perDict) {
    perDict = new Map();
    schemaCache.set(dictionary, perDict);
  }
  if (perDict.has(msgType)) {
    return perDict.get(msgType) || null;
  }

  const message = dictionary.messageByMsgType(msgType);
  if (!message) {
    perDict.set(msgType, null);
    return null;
  }

  const requiredComponentTags = new Map<string, Set<number>>();
  const expanded = expandMembers(
    dictionary,
    message.members,
    'Y',
    undefined,
    undefined,
    new Set(),
    { value: 0 },
    requiredComponentTags,
    false
  );

  const conditionalFields = expanded.fields.filter(
    (field) => field.reqd === 'C' && !field.isStarter
  );

  const schema: FixMessageSchema = {
    msgType: message.msgType,
    name: message.name,
    label: formatFixMessageName(message.name),
    fields: expanded.fields,
    groups: expanded.groups,
    fieldByTag: expanded.fieldByTag,
    groupByCounterTag: expanded.groupByCounterTag,
    orderedSlots: expanded.orderedSlots,
    conditionalFields,
    requiredComponentTags,
  };
  perDict.set(msgType, schema);
  return schema;
}

/**
 * Creates a clean starter draft for one application MsgType containing its
 * required fields and one starter entry for each required repeating group.
 */
export function createEmptyBuilderDraft(
  dictionary: FixDictionary,
  msgType: string
): FixBuilderDraft {
  const schema = getFixMessageSchema(dictionary, msgType);
  if (!schema) {
    return {
      msgType,
      fields: [],
      groups: [],
      strippedEnvelopeFields: [],
    };
  }

  const fields: FixBuilderField[] = schema.fields
    .filter((field) => field.isStarter)
    .map((field) => ({ tag: field.tag, value: '' }));

  const groups: FixBuilderGroup[] = schema.groups
    .filter((group) => group.isStarter)
    .map((group) => ({
      counterTag: group.counterTag,
      entries: [createEmptyGroupEntry(group)],
    }));

  return {
    msgType: schema.msgType,
    fields,
    groups,
    strippedEnvelopeFields: [],
  };
}

/**
 * Creates one starter entry for a repeating group with its delimiter tag pinned
 * first plus any required child fields and nested required groups.
 */
export function createEmptyGroupEntry(groupSchema: FixSchemaGroup): FixBuilderGroupEntry {
  const fields: FixBuilderField[] = [];
  const seen = new Set<number>();

  if (groupSchema.delimiterTag !== undefined) {
    fields.push({ tag: groupSchema.delimiterTag, value: '' });
    seen.add(groupSchema.delimiterTag);
  }

  for (const field of groupSchema.fields) {
    if (field.isStarter && !seen.has(field.tag)) {
      fields.push({ tag: field.tag, value: '' });
      seen.add(field.tag);
    }
  }

  const groups: FixBuilderGroup[] = groupSchema.groups
    .filter((nested) => nested.isStarter)
    .map((nested) => ({
      counterTag: nested.counterTag,
      entries: [createEmptyGroupEntry(nested)],
    }));

  return {
    id: createFixGroupEntryId(),
    fields,
    groups,
  };
}

/**
 * Hydrates a structured builder draft from raw wire or pipe-delimited FIX text.
 * Preserves unknown/custom fields, extracts repeating groups, strips session-managed
 * envelope tags (reporting them for optional inspection), and appends missing
 * required starter fields/groups.
 */
export function hydrateBuilderDraftFromRaw(
  raw: string,
  dictionary: FixDictionary | null | undefined
): FixBuilderDraft {
  const trimmed = raw.trim();
  if (!trimmed) {
    return {
      msgType: '',
      fields: [],
      groups: [],
      strippedEnvelopeFields: [],
    };
  }

  let rawFields: [string, string][];
  try {
    rawFields = parseFixDraftFields(trimmed, { maskSensitive: false });
  } catch (error) {
    return {
      msgType: '',
      fields: [],
      groups: [],
      strippedEnvelopeFields: [],
      parseError: error instanceof Error ? error.message : 'Invalid FIX message.',
    };
  }

  const strippedEnvelopeFields: Array<[number, string]> = [];
  const msgTypes: string[] = [];
  const bodyFields: [string, string][] = [];

  for (const [tagText, value] of rawFields) {
    const tag = Number(tagText);
    if (FIX_SESSION_ENVELOPE_TAGS.has(tag)) {
      strippedEnvelopeFields.push([tag, value]);
      continue;
    }
    if (tag === 35) {
      msgTypes.push(value);
      continue;
    }
    bodyFields.push([tagText, value]);
  }

  if (msgTypes.length === 0) {
    return {
      msgType: '',
      fields: bodyFields.map(([tagText, value]) => ({
        tag: Number(tagText),
        value,
        isExtra: true,
      })),
      groups: [],
      strippedEnvelopeFields,
      parseError: 'Message is missing MsgType tag 35.',
    };
  }

  if (msgTypes.length > 1) {
    return {
      msgType: '',
      fields: [],
      groups: [],
      strippedEnvelopeFields,
      parseError: 'Message contains more than one MsgType tag 35.',
    };
  }

  const msgType = msgTypes[0].trim();
  if (!msgType) {
    return {
      msgType: '',
      fields: [],
      groups: [],
      strippedEnvelopeFields,
      parseError: 'MsgType cannot be empty.',
    };
  }

  const dictMessage = dictionary?.messageByMsgType(msgType);
  if (FIX_ADMIN_MESSAGE_TYPES.has(msgType) || dictMessage?.category === 'admin') {
    return {
      msgType: '',
      fields: [],
      groups: [],
      strippedEnvelopeFields,
      adminMsgType: msgType,
    };
  }

  if (!dictionary) {
    return {
      msgType,
      fields: bodyFields.map(([tagText, value]) => ({
        tag: Number(tagText),
        value,
        isExtra: true,
      })),
      groups: [],
      strippedEnvelopeFields,
    };
  }

  const schema = getFixMessageSchema(dictionary, msgType);
  if (!schema) {
    return {
      msgType,
      fields: bodyFields.map(([tagText, value]) => ({
        tag: Number(tagText),
        value,
        isExtra: true,
      })),
      groups: [],
      strippedEnvelopeFields,
    };
  }

  const parsed = parseFixMessageForDisplay([['35', msgType], ...bodyFields], dictionary);
  const { fields, groups } = hydrateScopeFromNodes(
    parsed.nodes.filter((node) => !(node.kind === 'field' && node.tag === 35)),
    schema
  );

  return {
    msgType,
    fields,
    groups,
    strippedEnvelopeFields,
  };
}

/**
 * Transitions the builder to a new MsgType while preserving shared non-empty
 * values (across top-level fields and repeating groups), populating the new
 * MsgType's required fields/groups, keeping unmatched non-empty fields as extra,
 * and dropping unmatched empty fields.
 */
export function changeBuilderMsgType(
  current: FixBuilderDraft,
  nextMsgType: string,
  dictionary: FixDictionary
): FixBuilderDraft {
  const schema = getFixMessageSchema(dictionary, nextMsgType);
  if (!schema) {
    return {
      ...current,
      msgType: nextMsgType,
      parseError: undefined,
      adminMsgType: undefined,
    };
  }

  const topLevelNonEmpty = new Map<number, string>();
  const extraOrder: number[] = [];
  for (const field of current.fields) {
    if (field.value !== '') {
      if (!topLevelNonEmpty.has(field.tag)) {
        topLevelNonEmpty.set(field.tag, field.value);
        extraOrder.push(field.tag);
      }
    }
  }

  const anyTagNonEmpty = new Map<number, string>(topLevelNonEmpty);
  const existingGroupsByCounter = new Map<number, FixBuilderGroup>();
  collectNonEmptyFromGroups(current.groups, anyTagNonEmpty, existingGroupsByCounter);

  const consumedTopLevelTags = new Set<number>();
  const fields: FixBuilderField[] = [];

  for (const schemaField of schema.fields) {
    const carried = anyTagNonEmpty.get(schemaField.tag);
    if (carried !== undefined) {
      fields.push({ tag: schemaField.tag, value: carried });
      consumedTopLevelTags.add(schemaField.tag);
    } else if (schemaField.isStarter) {
      fields.push({ tag: schemaField.tag, value: '' });
    }
  }

  const groups: FixBuilderGroup[] = [];
  for (const groupSchema of schema.groups) {
    const existingGroup = existingGroupsByCounter.get(groupSchema.counterTag);
    const nonEmptyExisting = existingGroup
      ? existingGroup.entries.filter(hasNonEmptyGroupEntry)
      : [];

    if (nonEmptyExisting.length > 0) {
      const remappedEntries = nonEmptyExisting.map((entry) =>
        alignGroupEntryToSchema(entry, groupSchema)
      );
      groups.push({
        counterTag: groupSchema.counterTag,
        entries: remappedEntries,
      });
      for (const entry of remappedEntries) {
        for (const f of entry.fields) {
          if (f.value !== '') consumedTopLevelTags.add(f.tag);
        }
      }
    } else if (groupSchema.isStarter) {
      const starterEntry = createEmptyGroupEntry(groupSchema);
      for (const entryField of starterEntry.fields) {
        const carried = anyTagNonEmpty.get(entryField.tag);
        if (carried !== undefined) {
          entryField.value = carried;
          consumedTopLevelTags.add(entryField.tag);
        }
      }
      groups.push({
        counterTag: groupSchema.counterTag,
        entries: [starterEntry],
      });
    }
  }

  // Keep any non-empty top-level values that weren't matched in the new schema
  // as editable extra fields (dropping unmatched empty fields cleanly).
  for (const tag of extraOrder) {
    if (consumedTopLevelTags.has(tag)) continue;
    const value = topLevelNonEmpty.get(tag);
    if (value !== undefined && value !== '') {
      fields.push({ tag, value, isExtra: true });
    }
  }

  return {
    msgType: schema.msgType,
    fields,
    groups,
    strippedEnvelopeFields: current.strippedEnvelopeFields,
    parseError: undefined,
    adminMsgType: undefined,
  };
}

/**
 * Serializes a structured builder draft into a clean pipe-delimited FIX body.
 * Always places `35=<msgType>` first, omits empty fields/entries, auto-computes
 * repeating group counter tags, and preserves canonical dictionary wire order.
 */
export function serializeBuilderDraft(
  draft: FixBuilderDraft,
  dictionary?: FixDictionary | null
): string {
  const msgType = draft.msgType.trim();
  if (!msgType) return '';

  const pairs: Array<[number, string]> = [[35, msgType]];
  const schema = dictionary ? getFixMessageSchema(dictionary, msgType) : null;

  if (!schema) {
    for (const field of draft.fields) {
      if (field.value !== '' && field.tag !== 35) {
        pairs.push([field.tag, field.value]);
      }
    }
    for (const group of draft.groups) {
      appendGroupPairs(group, undefined, pairs);
    }
    return pairs.map(([tag, value]) => `${tag}=${value}`).join('|');
  }

  const schemaFieldsByTag = new Map<number, FixBuilderField[]>();
  const extraFields: FixBuilderField[] = [];
  for (const field of draft.fields) {
    if (field.tag === 35) continue;
    if (!field.isExtra && schema.fieldByTag.has(field.tag)) {
      const bucket = schemaFieldsByTag.get(field.tag) || [];
      bucket.push(field);
      schemaFieldsByTag.set(field.tag, bucket);
    } else {
      extraFields.push(field);
    }
  }

  const groupsByCounter = new Map<number, FixBuilderGroup>();
  const extraGroups: FixBuilderGroup[] = [];
  for (const group of draft.groups) {
    if (schema.groupByCounterTag.has(group.counterTag)) {
      groupsByCounter.set(group.counterTag, group);
    } else {
      extraGroups.push(group);
    }
  }

  for (const slot of schema.orderedSlots) {
    if (slot.kind === 'field') {
      const bucket = schemaFieldsByTag.get(slot.tag);
      if (!bucket) continue;
      for (const field of bucket) {
        if (field.value !== '') {
          pairs.push([field.tag, field.value]);
        }
      }
    } else {
      const group = groupsByCounter.get(slot.counterTag);
      const groupSchema = schema.groupByCounterTag.get(slot.counterTag);
      if (group) {
        appendGroupPairs(group, groupSchema, pairs);
      }
    }
  }

  for (const group of extraGroups) {
    appendGroupPairs(group, undefined, pairs);
  }
  for (const field of extraFields) {
    if (field.value !== '') {
      pairs.push([field.tag, field.value]);
    }
  }

  return pairs.map(([tag, value]) => `${tag}=${value}`).join('|');
}

/**
 * Evaluates blocking protocol errors (matching Raw mode) and non-blocking
 * dictionary warnings (missing required fields, empty required groups, or
 * group entries missing their delimiter tag).
 */
export function validateBuilderDraft(
  draft: FixBuilderDraft,
  dictionary?: FixDictionary | null
): FixBuilderValidation {
  if (draft.parseError) {
    return {
      blockingError: draft.parseError,
      missingRequired: [],
      delimiterWarnings: [],
    };
  }
  if (draft.adminMsgType) {
    return {
      blockingError:
        'Administrative FIX messages are managed automatically by the session.',
      missingRequired: [],
      delimiterWarnings: [],
    };
  }
  if (!draft.msgType.trim()) {
    return {
      blockingError: 'Select a MsgType (tag 35) before sending.',
      missingRequired: [],
      delimiterWarnings: [],
    };
  }

  const serialized = serializeBuilderDraft(draft, dictionary);
  const blockingError = validateFixDraft(serialized);
  const missingRequired: FixBuilderValidationIssue[] = [];
  const delimiterWarnings: FixBuilderValidationIssue[] = [];

  const schema = dictionary ? getFixMessageSchema(dictionary, draft.msgType) : null;
  if (!schema) {
    return { blockingError, missingRequired, delimiterWarnings };
  }

  const filledTopTags = new Set(
    draft.fields.filter((f) => f.value.trim() !== '').map((f) => f.tag)
  );
  const groupsByCounter = new Map(draft.groups.map((g) => [g.counterTag, g]));

  for (const schemaField of schema.fields) {
    if (!schemaField.isStarter) continue;
    if (filledTopTags.has(schemaField.tag)) continue;

    // If this field was promoted from a required component (e.g. 55 Symbol in
    // Instrument or 38 OrderQty in OrderQtyData), treat the component as satisfied
    // if ANY member tag of that component is filled.
    if (schemaField.reqd !== 'Y' && schemaField.requiredComponent) {
      const compTags = schema.requiredComponentTags.get(schemaField.requiredComponent);
      if (compTags && [...compTags].some((tag) => filledTopTags.has(tag))) {
        continue;
      }
    }

    missingRequired.push({
      tag: schemaField.tag,
      name: schemaField.name,
      reason:
        schemaField.reqd === 'Y'
          ? 'Required field is empty'
          : `Required component ${schemaField.requiredComponent || ''} has no fields filled`.trim(),
    });
  }

  for (const groupSchema of schema.groups) {
    const groupState = groupsByCounter.get(groupSchema.counterTag);
    validateGroupState(
      groupSchema,
      groupState,
      missingRequired,
      delimiterWarnings,
      undefined
    );
  }

  return { blockingError, missingRequired, delimiterWarnings };
}

/**
 * Searches unused fields and repeating groups that can be added to a message
 * or repeating-group entry scope, plus global dictionary tags and custom numeric tags.
 */
export function searchAddableSchemaMembers(
  scope: Pick<FixMessageSchema, 'fields' | 'groups' | 'fieldByTag' | 'groupByCounterTag'>,
  dictionary: FixDictionary,
  existingFieldTags: Set<number>,
  existingGroupTags: Set<number>,
  query: string
): FixAddableMemberOption[] {
  const trimmed = query.trim();
  const lower = trimmed.toLowerCase();
  const options: Array<{ option: FixAddableMemberOption; score: number }> = [];
  const seenTags = new Set<number>();

  // 1. Unused fields from the active message/group schema
  for (const field of scope.fields) {
    if (existingFieldTags.has(field.tag) || seenTags.has(field.tag)) continue;
    const matchScore = scoreFieldSearch(
      field.tag,
      field.name,
      field.componentPath,
      trimmed,
      lower
    );
    if (matchScore < 0) continue;
    seenTags.add(field.tag);
    const reqBoost = field.reqd === 'Y' ? 80 : field.reqd === 'C' ? 50 : 20;
    options.push({
      option: {
        kind: 'field',
        tag: field.tag,
        name: field.name,
        reqd: field.reqd,
        componentPath: field.componentPath,
        type: field.definition?.type,
        description: field.definition?.description,
        fromSchema: true,
      },
      score: matchScore + reqBoost,
    });
  }

  // 2. Unused repeating groups from the active message/group schema
  for (const group of scope.groups) {
    if (existingGroupTags.has(group.counterTag) || seenTags.has(group.counterTag)) continue;
    const matchScore = scoreFieldSearch(
      group.counterTag,
      group.name,
      group.componentPath,
      trimmed,
      lower
    );
    if (matchScore < 0) continue;
    seenTags.add(group.counterTag);
    const reqBoost = group.reqd === 'Y' ? 85 : group.reqd === 'C' ? 55 : 25;
    options.push({
      option: {
        kind: 'group',
        tag: group.counterTag,
        name: group.name,
        reqd: group.reqd,
        componentPath: group.componentPath,
        type: 'NumInGroup',
        description: group.definition?.description,
        fromSchema: true,
      },
      score: matchScore + reqBoost,
    });
  }

  // 3. When user types a query, also search global dictionary fields (e.g. optional
  // header tags like 50 SenderSubID or 57 TargetSubID)
  if (trimmed.length >= 1) {
    for (const field of dictionary.fieldsByTag.values()) {
      if (
        field.tag === 35 ||
        FIX_SESSION_ENVELOPE_TAGS.has(field.tag) ||
        existingFieldTags.has(field.tag) ||
        existingGroupTags.has(field.tag) ||
        seenTags.has(field.tag)
      ) {
        continue;
      }
      const matchScore = scoreFieldSearch(field.tag, field.name, undefined, trimmed, lower);
      if (matchScore < 0) continue;
      seenTags.add(field.tag);
      options.push({
        option: {
          kind: 'field',
          tag: field.tag,
          name: field.name,
          type: field.type,
          description: field.description,
          fromSchema: false,
        },
        score: matchScore - 40,
      });
    }
  }

  // 4. Custom numeric tag creation (e.g. proprietary broker tags 5000+)
  if (/^\d+$/.test(trimmed)) {
    const numericTag = Number(trimmed);
    if (
      numericTag > 0 &&
      numericTag !== 35 &&
      !FIX_SESSION_ENVELOPE_TAGS.has(numericTag) &&
      !existingFieldTags.has(numericTag) &&
      !existingGroupTags.has(numericTag) &&
      !seenTags.has(numericTag)
    ) {
      options.push({
        option: {
          kind: 'custom_tag',
          tag: numericTag,
          name: `Custom tag ${numericTag}`,
          fromSchema: false,
        },
        score: 900,
      });
    }
  }

  options.sort((a, b) => b.score - a.score || a.option.tag - b.option.tag);
  return options.slice(0, 60).map((entry) => entry.option);
}

